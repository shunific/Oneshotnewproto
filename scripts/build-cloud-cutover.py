#!/usr/bin/env python3
"""Build the review-only cloud cutover as one atomic transaction."""
from pathlib import Path
import argparse
import hashlib
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = (
    'customer-identity.draft.sql', 'cloud-containment.draft.sql',
    'private-receipts.draft.sql', 'booking-transactions.draft.sql',
    'booking-availability.draft.sql', 'staff-identity.draft.sql',
    'staff-payments.draft.sql', 'feedback-commands.draft.sql',
    'receipt-upload-intents.draft.sql',
    'staff-checkin.draft.sql', 'native-staff-authorization.draft.sql',
    'native-reservation-lifecycle.draft.sql', 'native-reservation-moves.draft.sql',
    'native-reservation-move-cancel.draft.sql',
)

def render():
    chunks = ['-- GENERATED by scripts/build-cloud-cutover.py; do not edit.\n'
              '-- REVIEW CANDIDATE ONLY. Review gates remain required.\n'
              '-- Apply all protections atomically; do not split this transaction.\nBEGIN;\n']
    for name in SOURCES:
        raw = (ROOT / 'security' / name).read_bytes()
        text = raw.decode('utf-8')
        begins = list(re.finditer(r'^\s*begin;\s*$', text, re.I | re.M))
        commits = list(re.finditer(r'^\s*commit;\s*$', text, re.I | re.M))
        if len(begins) != 1 or len(commits) != 1 or begins[0].end() >= commits[0].start():
            raise ValueError(f'{name}: expected exactly one outer BEGIN/COMMIT')
        for marker in (commits[0], begins[0]):
            text = text[:marker.start()] + text[marker.end():]
        chunks.append(f'\n-- SOURCE {name} SHA256 {hashlib.sha256(raw).hexdigest()}\n{text.rstrip()}\n')
    chunks.append('\nCOMMIT;\n')
    return ''.join(chunks)

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'security' / 'secure-cloud-cutover.generated.sql'
    expected = render()
    if args.check:
        if not target.exists() or target.read_text() != expected:
            parser.exit(1, 'Generated cloud cutover is stale; run this script.\n')
        print('PASS: atomic cutover matches all 14 source drafts')
    else:
        target.write_text(expected)
        print(f'Generated {target}')
